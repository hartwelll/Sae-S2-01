    public int getLigneId(int id){
        for(int i = 0; i < terrain.length; i++){
            for(int j = 0; j < terrain[0].length ; j++){
                if (terrain[i][j] == id) {
                    return i;
                }
            }
        }
        return -1;
    }

    public int getColId(int id){
        for(int i = 0; i < terrain.length; i++){
            for(int j = 0; j < terrain[0].length ; j++){
                if (terrain[i][j] == id) {
                    return j;
                }
            }
        }
        return -1;
    }


